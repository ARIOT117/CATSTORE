CREATE TABLE IF NOT EXISTS sc_menu_categorias (
 id VARCHAR(40) PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 nota VARCHAR(255) NOT NULL DEFAULT '',
 orden INT NOT NULL DEFAULT 0,
 activa TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sc_menu_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 clave VARCHAR(80) NOT NULL UNIQUE,
 categoria_id VARCHAR(40) NOT NULL,
 nombre VARCHAR(150) NOT NULL,
 descripcion TEXT NOT NULL,
 precio_centavos INT UNSIGNED NOT NULL,
 orden INT NOT NULL DEFAULT 0,
 disponible TINYINT NOT NULL DEFAULT 1,
 destacado_orden INT NULL DEFAULT NULL,
 FOREIGN KEY(categoria_id) REFERENCES sc_menu_categorias(id),
 KEY menu_orden(categoria_id,disponible,orden)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sc_migraciones (
 clave VARCHAR(100) PRIMARY KEY,
 aplicado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
